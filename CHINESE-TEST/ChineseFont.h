// 在指定位置繪製中文字
void drawChineseChar(int x, int y, uint16_t unicode, uint16_t color = GxEPD_BLACK) {
  for (int i = 0; i < CHINESE_FONT_COUNT; i++) {
    if (pgm_read_word(&chinese_fonts[i].unicode) == unicode) {
      const uint8_t* bitmap = chinese_fonts[i].bitmap;
      for (int row = 0; row < 16; row++) {
        for (int byte_idx = 0; byte_idx < 2; byte_idx++) {
          uint8_t row_data = pgm_read_byte(bitmap + row * 2 + byte_idx);
          for (int bit = 0; bit < 8; bit++) {
            if (!(row_data & (1 << (7 - bit)))) {
              // 修正：將 col 換回 (byte_idx * 8 + bit)，並使用 displayPtr->
              displayPtr->drawPixel(x + byte_idx * 8 + bit, y + row, color);
            }
          }
        }
      }
      return;
    }
  }
}

// 繪製中文字串
void drawChineseText(int x, int y, const char* text) {
  int offset_x = 0;
  while (*text) {
    uint8_t c = (uint8_t)*text;
    if (c >= 0xE4 && c <= 0xE9) {  // UTF-8 中文字範圍
      // UTF-8 中文字 (3 bytes)
      uint32_t unicode = ((uint32_t)c << 12) | ((uint8_t)text[1] << 6) | ((uint8_t)text[2]);
      unicode &= 0xFFFFF;
      drawChineseChar(x + offset_x, y, unicode);
      offset_x += 16;
      text += 3;
    } else {
      // ASCII
      text++;
    }
  }
}

